Somewhere around 150°F, a brisket stops climbing. You've done everything right — good fire, steady smoke, a probe
reading true — and then the number simply… stops. It sits there. For an hour. For three. Newcomers panic, crank the
heat, open the lid every five minutes to check whether the thermometer is broken. It isn't. What they're meeting, for
the first time, is the stall, and every pitmaster alive has stood exactly where they're standing.

### What's actually happening

It isn't magic and it isn't a fault — it's physics. As the meat heats, moisture is drawn to the surface and
evaporates, and evaporation cools. For a long stretch, the heat going *in* from the pit and the evaporative cooling
coming *off* the meat reach a near-standstill, and the internal temperature flatlines. It's the same reason sweat
cools you on a hot day, scaled up to a twelve-pound packer brisket. The fire hasn't quit. The meat is, in the most
literal sense, sweating it out.

### Wrap, or ride it out

Here's where barbecue splits into gentle religions. The **Texas crutch** — wrapping in foil, or in butcher paper —
traps that surface moisture, shuts the evaporation down, and drives the meat through the stall in a fraction of the
time. Foil is faster and softens the bark; butcher paper breathes a little, guarding the bark while still speeding
things along. And then there are the purists who wrap in nothing at all, ride the stall out for hours longer, and are
paid back with the firmest, darkest bark of the three.

There's no wrong answer. There's only the one your fire, your schedule, and your patience can agree on — and you'll
change your mind about it more than once over the years. That's allowed.

### The wider lesson

What the stall really teaches is the thing that sets barbecue apart from almost every other way we cook: you cannot
hurry it, and trying only makes it worse. It's the rare craft where doing *less*, for *longer*, is the entire secret.
The best cooks aren't the ones fighting the process — they're the ones who've made peace with it, poured another
coffee, and learned to trust that the fire knows what it's doing.

Maybe that's why a plate of it feels like more than dinner. Someone waited on your behalf.

